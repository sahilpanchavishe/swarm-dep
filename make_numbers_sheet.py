# make_numbers_sheet.py - single source of truth for every number in the paper.
# Recomputes from the data files; writes data/paper_numbers.md. Re-run after any change.
import csv, glob, json, math, os
from collections import Counter, defaultdict
from classifier import classify

G = ["CIRCLE", "LINE", "CLUSTER", "SPLIT", "STOP", "WAIT"]; WIN = 15
L = ["# Paper numbers (auto-generated by make_numbers_sheet.py - do not edit by hand)\n"]

def z(c1, n1, c2, n2):
    p = (c1 + c2) / (n1 + n2); se = math.sqrt(p * (1 - p) * (1 / n1 + 1 / n2))
    zz = (c1 / n1 - c2 / n2) / se if se else 0.0
    return zz, math.erfc(abs(zz) / math.sqrt(2))

def ci(k, n):  # Wilson 95%
    p = k / n; d = 1 + 1.96**2 / n; c = (p + 1.96**2 / (2 * n)) / d
    h = 1.96 * math.sqrt(p * (1 - p) / n + 1.96**2 / (4 * n * n)) / d
    return 100 * (c - h), 100 * (c + h)

# --- gesture recognition, per-frame and per-command (voted) ---
frame = defaultdict(lambda: [0, 0]); vote = defaultdict(lambda: [0, 0])
vcond = defaultdict(lambda: [0, 0]); vpart = defaultdict(lambda: [0, 0])
files = sorted(glob.glob("data/gesture_recordings_cb/*.csv"))
for path in files:
    name = os.path.basename(path).lower(); pid = name.split("_")[0].upper()
    cond = ("far" if "far" in name else "near") + "_" + ("dim" if "dim" in name else "bright")
    seq = defaultdict(list)
    for r in csv.DictReader(open(path)):
        g = r["intended_gesture"]
        if g not in G: continue
        x = [float(r[f"{a}{i}"]) for i in range(21) for a in "xyz"]
        p = classify(x, r.get("handedness", "Right")); seq[g].append(p)
        frame[g][1] += 1; frame[g][0] += (p == g)
    for g, ps in seq.items():
        for i in range(0, len(ps), WIN):
            w = ps[i:i + WIN]
            if len(w) < WIN // 2: continue
            ok = Counter(w).most_common(1)[0][0] == g
            for d, k in ((vote, g), (vcond, cond), (vpart, pid)):
                d[k][1] += 1; d[k][0] += ok
fk, fn = sum(v[0] for v in frame.values()), sum(v[1] for v in frame.values())
vk, vn = sum(v[0] for v in vote.values()), sum(v[1] for v in vote.values())
L.append("## Gesture recognition (8 participants, counterbalanced, 3 conditions)")
L.append(f"- Files: {len(files)}; frames: {fn}; command instances (window {WIN}): {vn}")
L.append(f"- Per-frame accuracy: {100*fk/fn:.1f}%   Per-command (voted) accuracy: {100*vk/vn:.1f}% (95% CI {ci(vk,vn)[0]:.1f}-{ci(vk,vn)[1]:.1f})")
L.append("- Per-gesture (voted): " + ", ".join(f"{g} {100*vote[g][0]/vote[g][1]:.1f}%" for g in G))
pv = [100 * v[0] / v[1] for v in vpart.values()]
m = sum(pv) / len(pv); sd = math.sqrt(sum((x - m)**2 for x in pv) / len(pv))
L.append(f"- Per-participant (voted): mean {m:.1f}%, SD {sd:.1f}, range {min(pv):.1f}-{max(pv):.1f}")
L.append("- Per-condition (voted): " + ", ".join(f"{c} {100*v[0]/v[1]:.1f}% (n={v[1]})" for c, v in sorted(vcond.items())))
with open("data/accuracy_by_condition_voted.csv", "w", newline="") as f:
    w = csv.writer(f); w.writerow(["condition", "accuracy_pct", "instances"])
    for c, v in sorted(vcond.items()): w.writerow([c, round(100 * v[0] / v[1], 2), v[1]])
cs = sorted(vcond)
for i in range(len(cs)):
    for j in range(i + 1, len(cs)):
        a, b = vcond[cs[i]], vcond[cs[j]]; zz, p = z(a[0], a[1], b[0], b[1])
        L.append(f"  - {cs[i]} vs {cs[j]}: z={zz:.2f}, p={p:.4f}")

# --- STOP channel (per hold: one camera, one classifier, one shared broadcast) ---
mw = json.load(open("data/misread_vs_window.json"))            # original dataset (thresholds were tuned on it)
pm = json.load(open("data/stop_misread_primary.json"))         # dedicated held-out STOP dataset = PRIMARY
L.append("\n## STOP channel (per gesture hold, shared by all robots)")
L.append(f"- PRIMARY: dedicated held-out STOP dataset, {len(pm['participants'])} participants, holds {pm['n_holds']}; second person confirmed each pose")
for e in pm["stop"]:
    if e["W"] in (1, 10, 25):
        L.append(f"  - window {e['W']} frames ({1000*e['delay_s']:.0f} ms): STOP misread {e['k']}/{e['n']} = {100*e['p']:.2f}% (95% CI {100*e['ci'][0]:.2f}-{100*e['ci'][1]:.2f})")
for er in pm["errors"]:
    L.append(f"  - error: {er['participant']} {er['condition']}: read as {er['read_as']} (frames {er['frames']})")
L.append("  - errors are spread over different people, conditions and wrong answers; dim vs other conditions not distinguishable (pooled 3/216 vs 2/422, Fisher p=0.34); confirmation window up to 10 frames does not remove them")
fs = pm["priority"][0]["false_stop"]
L.append(f"  - false STOP at W=1: LINE {fs['LINE'][0]}/{fs['LINE'][1]}, CLUSTER (OK-sign) {fs['CLUSTER'][0]}/{fs['CLUSTER'][1]}; original dataset CLUSTER 45/186 (differs by protocol: second-person pose check only in the dedicated set)")
L.append(f"  - this set was NOT used to tune the classifier thresholds, so it is an out-of-sample estimate")
L.append("- SUPPLEMENTARY: original dataset (rule thresholds tuned on it)")
for e in mw["stop"]:
    if e["W"] in (1, 15):
        L.append(f"  - window {e['W']} frames ({1000*e['delay_s']:.0f} ms): STOP misread {e['k']}/{e['n']} = {100*e['p']:.2f}% (95% CI {100*e['ci'][0]:.2f}-{100*e['ci'][1]:.2f}); all-gesture error {100*e['all_err']:.1f}%")
L.append("  - both original errors: P08, near_dim, read as LINE on every frame; NOT reproduced in the dedicated set (P08 near_dim 0/20)")
for e in mw["priority"]:
    if e["W"] in (1, 5, 15):
        L.append(f"  - STOP-priority (any STOP frame in first {e['W']}), original: missed STOP {100*e['missed']:.2f}%, false STOP on other gestures {100*e['false_stop']:.1f}%")

# --- corrected dependability sweep (sim_v2: shared misread, 30 Hz rebroadcast, Gilbert-Elliott) ---
R = list(csv.DictReader(open("data/study_v2.csv")))
L.append("\n## Dependability (sim_v2: shared misread, 30 Hz rebroadcast + latching, Gilbert-Elliott bursts, 400 seeds)")
L.append(f"- 0% loss: total violation = P(misread) = {100*float(R[0]['p_misread']):.2f}% for every N (no swarm-size effect)")
L.append("- Independent drops (mean burst 33 ms): violation stays at the misread floor up to 40% loss - rebroadcast defeats i.i.d. loss")
for b in ("0.1", "0.3", "1.0"):
    for loss in ("0.1", "0.2"):
        c = {r["N"]: r for r in R if r["common"] == "0.0" and r["burst_s"] == b and r["loss"] == loss}
        L.append(f"- burst {b} s, loss {float(loss)*100:.0f}%: " + ", ".join(
            f"N={N} {100*float(c[N]['total_violation']):.1f}% (analytic {100*float(c[N]['analytic_total']):.1f})" for N in ("8", "16", "32")))
ref = {r["N"]: r for r in R if r["common"] == "0.0" and r["burst_s"] == "0.3" and r["loss"] == "0.1"}
def kn(r): n = int(r["seeds"]); return round(float(r["p_loss_violation"]) * n), n
for a_, b_ in [("8", "16"), ("16", "32"), ("8", "32")]:
    zz, p = z(*kn(ref[a_]), *kn(ref[b_]))
    L.append(f"  - reference (0.3 s, 10%) N={a_} vs N={b_}: z={zz:.2f}, p={p:.2g}")
c5 = {(r["common"], r["N"]): r for r in R if r["burst_s"] == "0.3" and r["loss"] == "0.1"}
L.append(f"- Correlation matters: at 0.3 s/10%, N=32 independent {100*float(c5[('0.0','32')]['total_violation']):.1f}% vs half-shared bursts {100*float(c5[('0.5','32')]['total_violation']):.1f}%")

